/**
 * Parses user input into a valid YouTube videoId or playlistId.
 * Supports:
 * - Full YouTube URLs: https://www.youtube.com/watch?v=ijfLsKg8jFY
 * - Short URLs: https://youtu.be/ijfLsKg8jFY
 * - Playlist URLs: https://www.youtube.com/playlist?list=PLb5pq8p1HZfKusVbadzl7yHbR4atCXHe-
 * - URLs with list params: https://www.youtube.com/watch?v=xxx&list=yyy
 * - Direct Video IDs: ijfLsKg8jFY
 * - Direct Playlist IDs: PLb5pq8p1...
 */
export function parseYoutubeInput(input) {
  if (!input) return null
  const str = input.trim()

  // Check for playlist parameter
  const listMatch = str.match(/[?&]list=([a-zA-Z0-9_-]+)/)
  if (listMatch) {
    const vMatch = str.match(/(?:v=|youtu\.be\/|embed\/)([\w-]{11})/)
    return {
      type: 'playlist',
      playlistId: listMatch[1],
      videoId: vMatch ? vMatch[1] : null,
      rawInput: str,
    }
  }

  // Direct Playlist ID pattern (starts with PL, RD, UU, FL)
  if (/^(?:PL|RD|UU|FL)[a-zA-Z0-9_-]+$/.test(str)) {
    return {
      type: 'playlist',
      playlistId: str,
      videoId: null,
      rawInput: str,
    }
  }

  // Check for video URL pattern
  const vMatch = str.match(/(?:v=|youtu\.be\/|embed\/|shorts\/)([\w-]{11})/)
  if (vMatch) {
    return {
      type: 'video',
      videoId: vMatch[1],
      playlistId: null,
      rawInput: str,
    }
  }

  // Direct 11-char Video ID
  if (/^[a-zA-Z0-9_-]{11}$/.test(str)) {
    return {
      type: 'video',
      videoId: str,
      playlistId: null,
      rawInput: str,
    }
  }

  return null
}

/**
 * Auto-harmonizes audio mode to match the deity of the selected temple.
 *
 * @param {Object} temple
 * @returns {string} Matching track ID in YOUTUBE_BHAKTI_TRACKS
 */
export function getHarmonizedYoutubeTrack(temple) {
  if (!temple) return 'om_108'
  const d = (temple.deity || '').toLowerCase()
  const n = (temple.name || '').toLowerCase()
  const c = (temple.circuit_tags || []).join(' ').toLowerCase()

  if (d.includes('shiva') || n.includes('shiva') || n.includes('mahadev') || c.includes('jyotirlinga')) {
    return Math.random() > 0.5 ? 'maha_mrityunjaya' : 'shiv_tandav'
  }
  if (d.includes('hanuman') || n.includes('hanuman') || n.includes('balaji')) {
    return 'hanuman_chalisa'
  }
  if (d.includes('krishna') || n.includes('krishna') || n.includes('radha') || n.includes('govind') || n.includes('iskcon')) {
    return Math.random() > 0.5 ? 'krishna_flute' : 'achyutam_keshavam'
  }
  if (d.includes('ram') || n.includes('ram') || n.includes('ayodhya') || c.includes('ram circuit')) {
    return 'ram_bhajan'
  }
  if (d.includes('vishnu') || n.includes('venkateswara') || n.includes('balaji') || n.includes('jagannath') || n.includes('tirupati')) {
    return 'vishnu_sahasranamam'
  }
  if (d.includes('goddess') || d.includes('devi') || c.includes('shakti peetha') || n.includes('durga') || n.includes('kali') || n.includes('mata')) {
    return Math.random() > 0.5 ? 'gayatri_mantra' : 'ganga_aarti'
  }
  if (d.includes('surya') || n.includes('sun temple') || n.includes('konark') || n.includes('martand')) {
    return 'gayatri_mantra'
  }

  return 'om_108'
}
