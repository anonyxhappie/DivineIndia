/**
 * Helper to fetch curated lore by slug or temple name
 */
export function getCuratedLore(temple) {
  if (!temple) return null
  const slug = temple.wiki_slug
  const name = temple.name

  if (slug && CURATED_LORE[slug]) {
    return CURATED_LORE[slug]
  }

  // Check by formatted name key
  const nameKey = name ? name.replace(/\s+/g, '_') : ''
  if (nameKey && CURATED_LORE[nameKey]) {
    return CURATED_LORE[nameKey]
  }

  // Check case-insensitive / partial matches
  for (const [key, val] of Object.entries(CURATED_LORE)) {
    if (
      slug?.toLowerCase() === key.toLowerCase() ||
      name?.toLowerCase() === key.toLowerCase() ||
      name?.toLowerCase() === key.replace(/_/g, ' ').toLowerCase()
    ) {
      return val
    }
  }

  return null
}
